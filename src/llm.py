import os
import requests
from dotenv import load_dotenv

load_dotenv()

def generate_llm_explanation(payload, result, reasons):
    api_key = os.getenv("GEMINI_API_KEY","").strip()
    if not api_key:
        return (
            "**Local analyst summary**\n\n"
            f"The ensemble model assigned **{result['risk_band']} risk** with an estimated fraud probability of **{result['risk_score']:.1%}**. "
            f"Recommended next step: **{result['recommendation']}**.\n\n"
            "**Signals to review:**\n" + "\n".join([f"- {r}" for r in reasons]) +
            "\n\nThis is a synthetic demonstration. Verify transaction context before taking action."
        ), "Local fallback explanation used. Add GEMINI_API_KEY to .env to enable Gemini."
    prompt = f"""
You are an assistant helping a fraud operations analyst understand a machine-learning risk score.
Explain the assessment in clear, cautious language. Do not claim fraud is proven. Do not invent facts.
State the predicted risk band, probability, key signals, and a sensible human-review next step.
Transaction features: {payload}
Model output: {result}
Signals: {reasons}
Keep the response under 180 words.
"""
    try:
        url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-2.0-flash:generateContent?key={api_key}"
        response = requests.post(url,json={"contents":[{"parts":[{"text":prompt}]}]},timeout=25)
        response.raise_for_status()
        data = response.json()
        text = data["candidates"][0]["content"]["parts"][0]["text"]
        return text, "Explanation generated by Gemini. The ML model—not the LLM—produced the risk probability."
    except Exception as exc:
        return (
            "**Local analyst summary**\n\n"
            f"The ensemble model assigned **{result['risk_band']} risk** with an estimated fraud probability of **{result['risk_score']:.1%}**. "
            f"Recommended next step: **{result['recommendation']}**.\n\n" +
            "\n".join([f"- {r}" for r in reasons]) +
            f"\n\nGemini was unavailable ({type(exc).__name__}); local explanation shown instead."
        ), "Local fallback explanation used."
